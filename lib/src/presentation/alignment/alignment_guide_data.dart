// 축 정렬 현장 지침: 현장이 늘 좋은 조건이 아니라서 생기는 일들을 경우별로 모았다(증상 → 원인 → 대책 → 확인).
// 현장에서 가장 흔한 원인은 배관이 당기거나 용접으로 틀어지는 것이라 '배관·용접'을 따로 두었다.
// 여러 현장에서 흔히 쓰는 요령을 정리한 것이고, 제조사 매뉴얼·사내 절차가 있으면 그것이 먼저다.

enum AlignGuideCat {
  prepare('준비'),
  pipe('배관·용접'),
  measure('측정'),
  machine('기계·자리'),
  environment('환경'),
  shim('심·조정'),
  finish('마무리');

  final String label;
  const AlignGuideCat(this.label);
}

class AlignTip {
  final String id;
  final AlignGuideCat cat;
  final String title;
  final String symptom; // 이럴 때
  final List<String> causes; // 흔한 원인
  final List<String> fixes; // 대책
  final String check; // 됐는지 보는 법
  final List<String> words; // 찾기용 말
  const AlignTip({
    required this.id,
    required this.cat,
    required this.title,
    required this.symptom,
    required this.causes,
    required this.fixes,
    required this.check,
    this.words = const [],
  });

  bool matches(String q) {
    final t = q.trim();
    if (t.isEmpty) return true;
    bool has(String s) => s.contains(t);
    return has(title) || has(symptom) || causes.any(has) || fixes.any(has) || has(check) || words.any(has);
  }
}

