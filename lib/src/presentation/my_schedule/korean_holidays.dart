String _two(int v) => v.toString().padLeft(2, '0');

// 그 날이 공휴일이면 이름, 아니면 빈 글자.
String holidayName(DateTime day) =>
    kKoreanHolidays['${day.year}-${_two(day.month)}-${_two(day.day)}'] ?? '';

bool isKoreanHoliday(DateTime day) => holidayName(day).isNotEmpty;

// 표에 들어 있는 마지막 해(이 해가 지나면 공휴일 표시가 비니 표를 채워야 한다).
int get lastHolidayYear => kKoreanHolidays.keys
    .map((k) => int.parse(k.substring(0, 4)))
    .fold(0, (a, b) => a > b ? a : b);
