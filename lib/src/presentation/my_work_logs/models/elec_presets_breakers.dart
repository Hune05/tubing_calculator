/// 극수별 한 줄: (극 수, 가로, 세로, 깊이).
typedef _Row = (int, double, double, double);

List<ModulePreset> _mccb(
  String series,
  String maker,
  String style,
  List<_Row> rows,
) => [
  for (final (p, w, h, d) in rows)
    ModulePreset(
      '$series ${p}P ($maker)',
      w,
      h,
      shape: '${ElecShape.mccb}:$style:$p',
      depth: d,
    ),
];

List<ModulePreset> _acb(
  String series,
  String maker,
  String style,
  List<_Row> rows,
