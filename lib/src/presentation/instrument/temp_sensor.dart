//
// - 백금 측온저항체 Pt100·Pt1000: IEC 60751:2022 Callendar–Van Dusen 식(α = 0.00385).
// - 열전대 K·J·T·E·N·R·S·B: NIST ITS-90 열전대 데이터베이스(Monograph 175) 기준 함수와 역함수.
//   IEC 60584-1:2013도 같은 식이다. 계수는 NIST 파일(allcoeff.tab)에서 그대로 옮겼다.
// 적용 범위를 벗어나면 null을 돌려준다(화면은 "범위 초과"·"범위 미만").
library;

import 'dart:math' as math;

/// 센서 종류.
enum TempSensor { pt100, pt1000, k, j, t, e, n, r, s, b }

extension TempSensorInfo on TempSensor {
  bool get isRtd => this == TempSensor.pt100 || this == TempSensor.pt1000;

  /// 화면·성적서 이름: Pt100, Pt1000, K형 …
  String get label => switch (this) {
    TempSensor.pt100 => 'Pt100',
    TempSensor.pt1000 => 'Pt1000',
    _ => '${name.toUpperCase()}형',
  };

  /// 센서 값의 단위: 측온저항체는 Ω, 열전대는 mV.
  String get unit => isRtd ? 'Ω' : 'mV';

  /// 기준 규격.
  String get standard => isRtd ? 'IEC 60751' : 'IEC 60584-1';

  /// 0 °C 저항(측온저항체).
  double get r0 => this == TempSensor.pt1000 ? 1000 : 100;

  /// 온도 → 센서 값 적용 범위(°C).
  (double, double) get tempRange {
    if (isRtd) return (kRtdMinC, kRtdMaxC);
    final c = _tc[this]!;
    return (c.ref.first.lo, c.ref.last.hi);
  }

  /// 센서 값 → 온도 적용 범위(°C). 열전대는 NIST 역함수 범위.
  (double, double) get inverseTempRange {
    if (isRtd) return (kRtdMinC, kRtdMaxC);
    final c = _tc[this]!;
    return (c.inv.first.tLo, c.inv.last.tHi);
  }

  /// 센서 값 → 온도에 넣을 수 있는 값의 범위(Ω 또는 mV, 기준접점 0 °C).
  (double, double) get valueRange {
    final (lo, hi) = inverseTempRange;
    return (sensorValue(this, lo)!, sensorValue(this, hi)!);
  }
}

/// 측정 범위 단위가 섭씨인지(°C, ℃, C, degC).
bool isCelsiusUnit(String unit) {
  final u = unit.trim().toLowerCase().replaceAll(' ', '');
  return const {'°c', '℃', 'ºc', 'c', 'degc'}.contains(u);
}

// ─────────────── 측온저항체(IEC 60751) ───────────────

/// Callendar–Van Dusen 계수(IEC 60751, α = 0.00385).
const double kCvdA = 3.9083e-3;
const double kCvdB = -5.775e-7;
const double kCvdC = -4.183e-12; // 0 °C 아래에서만
const double kRtdMinC = -200;
const double kRtdMaxC = 850;

double _cvd(double t, double r0) => t < 0
    ? r0 * (1 + kCvdA * t + kCvdB * t * t + kCvdC * (t - 100) * t * t * t)
    : r0 * (1 + kCvdA * t + kCvdB * t * t);

double _cvdD(double t, double r0) => t < 0
    ? r0 * (kCvdA + 2 * kCvdB * t + kCvdC * (4 * t * t * t - 300 * t * t))
    : r0 * (kCvdA + 2 * kCvdB * t);

/// 온도(°C) → 저항(Ω). 범위(−200 ~ 850 °C)를 벗어나면 null.
double? rtdOhm(double tC, {double r0 = 100}) {
  if (tC < kRtdMinC - 1e-9 || tC > kRtdMaxC + 1e-9) return null;
  return _cvd(tC, r0);
}

/// 저항(Ω) → 온도(°C). 0 °C 이상은 2차식의 근, 0 °C 아래는 뉴턴 반복. 범위를 벗어나면 null.
double? rtdTemp(double ohm, {double r0 = 100}) {
  final lo = _cvd(kRtdMinC, r0), hi = _cvd(kRtdMaxC, r0);
  if (ohm < lo - 1e-9 || ohm > hi + 1e-9) return null;
  var t =
      (-kCvdA + math.sqrt(kCvdA * kCvdA - 4 * kCvdB * (1 - ohm / r0))) /
      (2 * kCvdB);
  if (ohm < r0) {
    for (var i = 0; i < 50; i++) {
      final dt = (_cvd(t, r0) - ohm) / _cvdD(t, r0);
      t -= dt;
      if (dt.abs() < 1e-10) break;
    }
  }
  return t.clamp(kRtdMinC, kRtdMaxC).toDouble();
}

// ─────────────── 열전대(NIST ITS-90) ───────────────

class _Poly {
  final double lo, hi; // 온도 범위(°C)
  final List<double> c; // E = Σ c_i·t^i (mV)
  const _Poly(this.lo, this.hi, this.c);
}

class _Inv {
  final double tLo, tHi; // 온도 범위(°C)
  final double vLo, vHi; // 전압 범위(mV)
  final List<double> d; // t = Σ d_i·E^i
  const _Inv(this.tLo, this.tHi, this.vLo, this.vHi, this.d);
}

class _TcCoef {
  final List<_Poly> ref;
  final List<double>? exp; // K형 0 °C 이상: a0·exp(a1·(t − a2)²)
  final List<_Inv> inv;
  const _TcCoef({required this.ref, this.exp, required this.inv});
}

double _horner(List<double> c, double x) {
  var s = 0.0;
  for (var k = c.length - 1; k >= 0; k--) {
    s = s * x + c[k];
  }
  return s;
}

double _hornerD(List<double> c, double x) {
  var s = 0.0;
  for (var k = c.length - 1; k >= 1; k--) {
    s = s * x + k * c[k];
  }
  return s;
}

_Poly _segment(_TcCoef c, double t) {
  for (final p in c.ref) {
    if (t < p.hi) return p;
  }
  return c.ref.last;
}

/// 범위 검사 없이 기준 함수 값(뉴턴 반복용).
double _emfRaw(_TcCoef c, double t) {
  var e = _horner(_segment(c, t).c, t);
  final a = c.exp;
  if (a != null && t >= 0) e += a[0] * math.exp(a[1] * (t - a[2]) * (t - a[2]));
  return e;
}

double _emfD(_TcCoef c, double t) {
  var g = _hornerD(_segment(c, t).c, t);
  final a = c.exp;
  if (a != null && t >= 0) {
    g +=
        a[0] * math.exp(a[1] * (t - a[2]) * (t - a[2])) * 2 * a[1] * (t - a[2]);
  }
  return g;
}

/// 열전대 열기전력(mV, 기준접점 0 °C). 열전대가 아니거나 범위를 벗어나면 null.
double? tcEmf(TempSensor s, double tC) {
  final c = _tc[s];
  if (c == null) return null;
  if (tC < c.ref.first.lo - 1e-9 || tC > c.ref.last.hi + 1e-9) return null;
  return _emfRaw(c, tC);
}

/// 열기전력(mV, 기준접점 0 °C) → 온도(°C). NIST 역함수로 첫 값을 구하고 기준 함수로 뉴턴 반복해
/// 기준 함수와 맞춘다(역함수만 쓰면 오차 최대 ±0.06 °C). 역함수 범위를 벗어나면 null.
double? tcTemp(TempSensor s, double mV) {
  final c = _tc[s];
  if (c == null) return null;
  final tLo = c.inv.first.tLo, tHi = c.inv.last.tHi;
  if (mV < _emfRaw(c, tLo) - 1e-9 || mV > _emfRaw(c, tHi) + 1e-9) return null;
  _Inv? seg;
  for (final v in c.inv) {
    // NIST 전압 범위는 소수 셋째 자리까지라 경계에서 조금 넓혀 고른다.
    if (mV >= v.vLo - 0.001 && mV <= v.vHi + 0.001) {
      seg = v;
      break;
    }
  }
  var t = _horner((seg ?? c.inv.last).d, mV);
  for (var i = 0; i < 50; i++) {
    final dt = (_emfRaw(c, t) - mV) / _emfD(c, t);
    t -= dt;
    if (dt.abs() < 1e-10) break;
  }
  return t.clamp(tLo, tHi).toDouble();
}

// ─────────────── 공통 ───────────────

/// 온도 → 센서 값(Ω 또는 기준접점 0 °C mV). 범위를 벗어나면 null.
double? sensorValue(TempSensor s, double tC) =>
    s.isRtd ? rtdOhm(tC, r0: s.r0) : tcEmf(s, tC);

/// 센서 값(Ω 또는 기준접점 0 °C mV) → 온도. 범위를 벗어나면 null.
double? sensorTemp(TempSensor s, double v) =>
    s.isRtd ? rtdTemp(v, r0: s.r0) : tcTemp(s, v);

/// 교정기에 넣을 값. 측온저항체는 Ω, 열전대는 E(t) − E(냉접점)(mV).
/// 온도나 냉접점 온도가 범위를 벗어나면 null.
double? calibratorValue(TempSensor s, double tC, {double cjC = 0}) {
  final v = sensorValue(s, tC);
  if (v == null || s.isRtd) return v;
  final cj = tcEmf(s, cjC);
  return cj == null ? null : v - cj;
}

/// 단자에서 측정한 값 → 온도. 열전대는 측정 mV + E(냉접점)을 역산한다.
double? tempFromMeasured(TempSensor s, double v, {double cjC = 0}) {
  if (s.isRtd) return rtdTemp(v, r0: s.r0);
  final cj = tcEmf(s, cjC);
  return cj == null ? null : tcTemp(s, v + cj);
}

