/// 한 칸. [rows]는 (머리말, 내용 — 줄바꿈마다 한 항목), [steps]는 번호 순서, [trouble]은 (현상, 원인, 조치).
class _Part {
  final String name;
  final List<(String, String)> rows;
  final List<String> steps;
  final List<(String, String, String)> trouble;
  final String? warn;
  final String? tip;
  final Widget Function(BuildContext context)? extra;
  const _Part(
    this.name, {
    this.rows = const [],
    this.steps = const [],
    this.trouble = const [],
    this.warn,
    this.tip,
    this.extra,
  });
}

class _Guide {
  final String id;
  final _Group group;
  final String title;
  final String sub;
  final IconData icon;
  final Color color;
  final List<_Part> parts;
  final Widget Function(BuildContext context)? footer; // 설명서 단추 등
  const _Guide({
    required this.id,
    required this.group,
    required this.title,
    required this.sub,
    required this.icon,
    required this.color,
    required this.parts,
    this.footer,
  });
}

Widget _manualButton({required Key key, required String label, required VoidCallback onTap, required Color color}) {
  return SizedBox(
    width: double.infinity,
    child: OutlinedButton.icon(
      key: key,
      onPressed: onTap,
      icon: const Icon(LucideIcons.bookOpen, size: 18),
      label: Text(label, style: const TextStyle(fontWeight: FontWeight.w700)),
      style: OutlinedButton.styleFrom(
        foregroundColor: color,
        side: BorderSide(color: color),
        padding: const EdgeInsets.symmetric(vertical: 12),
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(10)),
      ),
    ),
  );
}

